/**
 * Resolves any route string (or hash path) into target tab state.
 * Supports /path, #/path, or route IDs.
 */
export function resolveRoute(routeString) {
  if (!routeString) return null;
  const clean = routeString.replace(/^#/, '').trim().toLowerCase();

  // 1. Direct match on route
  const foundByRoute = APP_ROUTES.find((r) => r.route.toLowerCase() === clean);
  if (foundByRoute) return foundByRoute;

  // 2. Direct match on id
  const foundById = APP_ROUTES.find((r) => r.id.toLowerCase() === clean);
  if (foundById) return foundById;

  // 3. Prefix match
  const foundByPrefix = APP_ROUTES.find((r) => clean.startsWith(r.route.toLowerCase()));
  if (foundByPrefix) return foundByPrefix;

  return null;
}

/**
 * Generates route string for given tab, subTab, subSubTab state
 */
export function getRouteForTab(tab, subTab, subSubTab) {
  const match = APP_ROUTES.find((r) => {
    if (r.tab !== tab) return false;
    if (subTab && r.subTab && r.subTab !== subTab) return false;
    if (subSubTab && r.subSubTab && r.subSubTab !== subSubTab) return false;
    return true;
  });
  return match ? match.route : `/${tab}`;
}
